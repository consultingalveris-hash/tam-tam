// Nouvel écran d'appel (icônes en haut à droite), ajouter quelqu'un pendant un appel à deux, appel depuis la sélection de discussions.
import { B, mk, reg, inv, done } from './lib.mjs';
const out = (k, v) => console.log(k, typeof v === 'string' ? v : JSON.stringify(v));
const d = await mk('D'); await reg(d, B, 'desire', 'Désiré', 'owner@exemple.org');
const a = await mk('A'); await reg(a, await inv(d), 'awa', 'Awa', 'awa@exemple.org');
const m = await mk('M'); await reg(m, await inv(d), 'moussa', 'Moussa', 'moussa@exemple.org');
const [aId, mId] = [await a.evaluate(() => S.me.id), await m.evaluate(() => S.me.id)];
const chatId = await d.evaluate(async id => { const x = await api('/api/chats/direct', {userId: id}); await loadChats(); await loadContacts(); return x.chat.id; }, aId);
for (const p of [a, m]) await p.evaluate(async () => { await loadChats(); await loadContacts(); });
await d.evaluate(cid => openChat(cid), chatId); await d.waitForTimeout(300);
await d.evaluate(() => Call.start(false)); await a.waitForTimeout(2500);
await a.evaluate(() => Call.accept()); await a.waitForTimeout(3500);
out('appel vocal établi :', await d.evaluate(() => Call.c && Call.c.state));
out('icônes (vocal) :', await d.evaluate(() => [...document.querySelectorAll('#call .call-side .ci')].map(x => x.getAttribute('aria-label') + (x.classList.contains('off') ? ' [barré]' : ''))));
out('plus de textes sous les boutons :', await d.evaluate(() => document.querySelectorAll('#call .cb span').length === 0 && !document.querySelector('#call .call-side span')));
await d.click('[data-act=callMic]'); await d.waitForTimeout(200);
out('micro coupé → barré :', await d.evaluate(() => document.querySelector('[data-act=callMic]').classList.contains('off')));
await d.click('[data-act=callMic]'); await d.waitForTimeout(200);
out('micro rallumé → plus barré :', await d.evaluate(() => !document.querySelector('[data-act=callMic]').classList.contains('off')));
await d.screenshot({path: 'shots/c212-vocal.png'});
await d.click('[data-act=callAdd]'); await d.waitForTimeout(400);
out('liste pour ajouter :', await d.evaluate(() => [...document.querySelectorAll('.cp-row .cp-n')].map(x => x.textContent)));
await d.screenshot({path: 'shots/c212-ajout.png'});
await d.evaluate(id => document.querySelector(`.cp-row[data-id="${id}"]`).click(), mId); await d.waitForTimeout(3000);
out('Moussa sonne :', await m.evaluate(() => !!GCall.inc));
out('Désiré et Awa passés en appel de groupe :', [await d.evaluate(() => [!!GCall.c, !!Call.c]), await a.evaluate(() => [!!GCall.c, !!Call.c])]);
await m.evaluate(() => GCall.accept()); await m.waitForTimeout(4500);
out('à trois :', await d.evaluate(() => GCall.c && GCall.c.peers.size + 1));
out('icônes (groupe) + point de disposition :', await d.evaluate(() => [[...document.querySelectorAll('#gcall .call-side .ci')].length, !!document.querySelector('#gcall .g-laydot')]));
await d.screenshot({path: 'shots/c212-groupe.png'});
for (const p of [d, a, m]) await p.evaluate(() => GCall.c && GCall.leave()); await d.waitForTimeout(1200);
// appel depuis la sélection de discussions
await d.evaluate(() => { closeLayer && closeLayer(); ACT.back && S.chatId && ACT.back(); S.tab = 'chats'; renderAll(); });
const mChat = await d.evaluate(async id => (await api('/api/chats/direct', {userId: id})).chat.id, mId);
await d.evaluate(async ids => { await loadChats(); S.sel = new Set(ids); renderBody(); ACT.selMenu(); }, [chatId, mChat]); await d.waitForTimeout(300);
out('menu sélection :', await d.evaluate(() => [...document.querySelectorAll('.menu button')].slice(0, 3).map(b => b.textContent.trim())));
await d.screenshot({path: 'shots/c212-menu.png'});
await d.click('[data-act=selCall][data-v="1"]'); await d.waitForTimeout(3000);
out('appel vidéo de groupe lancé :', [await d.evaluate(() => !!GCall.c && S.chats.get(GCall.c.chatId).name), await a.evaluate(() => !!GCall.inc), await m.evaluate(() => !!GCall.inc)]);
await d.evaluate(() => GCall.leave());
await done();
